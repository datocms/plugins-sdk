import * as fs from 'node:fs';
import { createRequire } from 'node:module';

// The type lists only the canonical names of icon-nodes.json. The aliases
// are the old names of the icons that Lucide renamed: they are not in the
// list of https://lucide.dev/icons, and a major of Lucide can remove them.
const require = createRequire(import.meta.url);
const { version } = require('lucide-static/package.json') as {
  version: string;
};
const names = Object.keys(
  require('lucide-static/icon-nodes.json') as Record<string, unknown>,
).sort();

const output = `// Generated by generateLucideIconNames.ts from lucide-static ${version}. Do not edit.
// Run "npm run sdk:icon-names" in the root of the repository to write it again.

/**
 * The name of an icon of Lucide (https://lucide.dev/icons), for example
 * \`"book-open"\`. DatoCMS draws it with the stroke and the color of the rest
 * of the interface.
 */
export type LucideIconIdentifier =
${names.map((name) => `  | '${name}'`).join('\n')};
`;

fs.writeFileSync(
  new URL('./src/lucideIconIdentifier.ts', import.meta.url),
  output,
);

console.log(`Wrote ${names.length} icon names of lucide-static ${version}.`);
